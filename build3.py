def hdr(ws,row,labels,widths):
    for i,(t,w) in enumerate(zip(labels,widths),1):
        c=ws.cell(row=row,column=i,value=t)
        c.font=Font(name=F,bold=True,color="FFFFFF",size=10); c.fill=HDR; c.border=BOX
        c.alignment=Alignment(horizontal="center",vertical="center",wrap_text=True)
        ws.column_dimensions[get_column_letter(i)].width=w
    ws.row_dimensions[row].height=30

def body(ws,r0,rows,fills=None,wrap=(),center=()):
    for ri,row in enumerate(rows):
        for ci,v in enumerate(row,1):
            c=ws.cell(row=r0+ri,column=ci,value=v)
            c.font=Font(name=F,size=10); c.border=BOX
            c.alignment=Alignment(vertical="top",wrap_text=(ci in wrap),
                                  horizontal="center" if ci in center else "left")
        if fills and fills[ri]:
            for ci in range(1,len(row)+1): ws.cell(row=r0+ri,column=ci).fill=fills[ri]

